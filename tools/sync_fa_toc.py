#!/usr/bin/env python
"""Regenerate the Persian table of contents from the English one.

    python tools/sync_fa_toc.py

Every entry of the English `myst.yml` is copied into `fa/myst.yml`; an entry is
left active when its page exists under `fa/` and commented out otherwise, so the
Persian edition lists exactly the pages that are translated and the rest stay as
the visible translation plan. Run it after adding a translated page.

Group titles are translated by the table below; add an entry there when a new
group appears in `myst.yml`.
"""

from __future__ import annotations

import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]

TITLES = {
    "Foundations": "مبانی",
    "Simple Methods and High Dimension": "روش‌های ساده و داده‌های با ابعاد بالا",
    "Linear Models and Neural Networks": "مدل‌های خطی و شبکه‌های عصبی",
    "Dimensionality Reduction": "کاهش بُعد",
    "Kernel Methods": "روش‌های هسته",
    "Bayesian and Statistical Learning": "یادگیری بیزی و آماری",
    "Latent Variable Models": "مدل‌های متغیر پنهان",
    "Other Topics": "موضوع‌های دیگر",
    "Course Plan Fall 2026 & Project": "برنامهٔ درس (پاییز ۱۴۰۵) و پروژه",
    "Appendix": "پیوست",
}


def persian_path(english: str) -> str:
    """`notebooks/x/y.md` (English) -> `x/y.md` (Persian); other directories stay as they are."""
    return english.removeprefix("notebooks/")


def main() -> int:
    toc = yaml.safe_load((ROOT / "myst.yml").read_text(encoding="utf-8"))["project"]["toc"]
    lines = [
        "  toc:",
        "    # Generated by tools/sync_fa_toc.py from the English table of contents:",
        "    # an entry is active once the page exists under fa/, commented otherwise.",
    ]
    active = 0
    for item in toc:
        if "file" in item:
            lines.append(f"    - file: {persian_path(item['file'])}")
            active += 1
            continue
        lines.append(f"    - title: {TITLES.get(item['title'], item['title'])}")
        lines.append("      children:")
        for child in item["children"]:
            rel = persian_path(child["file"])
            if (ROOT / "fa" / rel).exists():
                lines.append(f"        - file: {rel}")
                active += 1
            else:
                lines.append(f"        # - file: {rel}")

    path = ROOT / "fa" / "myst.yml"
    text = path.read_text(encoding="utf-8")
    head, rest = text.split("\n  toc:\n", 1)
    tail = "\nsite:\n" + rest.split("\nsite:\n", 1)[1]
    path.write_text(head + "\n" + "\n".join(lines) + "\n" + tail, encoding="utf-8")
    print(f"[fa/myst.yml] {active} active entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
